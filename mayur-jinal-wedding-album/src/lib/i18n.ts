export function getLang(): Lang {
  if (typeof window === 'undefined') return DEFAULT_LANG;
  // Prefer cookie for SSR consistency
  const cookieMatch = document.cookie.match(/(?:^|; )lang=([^;]+)/);
  const fromCookie = cookieMatch ? decodeURIComponent(cookieMatch[1]) : '';
  const stored = (localStorage.getItem('lang') as Lang) || '';
  const v = (fromCookie as Lang) || (stored as Lang) || DEFAULT_LANG;
  return v === 'gu' ? 'gu' : 'en';
}

export function t(key: string, lang?: Lang): string {
  const l = lang || getLang();
  const dict = l === 'gu' ? gu : en;
  return dict[key] ?? key;
}


